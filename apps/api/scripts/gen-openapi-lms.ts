// Generates src/openapi-lms.ts: the OpenAPI entries for the LMS routes, read from the route
// files (method, path, permission, the Zod schema the handler parses, and the comment above
// it as the summary). Run after adding LMS routes: npx tsx scripts/gen-openapi-lms.ts
import fs from 'node:fs';
import path from 'node:path';

const src = path.join(import.meta.dirname, '..', 'src', 'routes');
const FILES = {
  'courses.ts': ['/api', 'Courses'],
  'assessments.ts': ['/api', 'Assessments'],
  'quizzes.ts': ['/api', 'Quizzes'],
  'gradebook.ts': ['/api', 'Gradebook'],
  'attendance.ts': ['/api', 'Attendance'],
  'timetable.ts': ['/api', 'Timetable'],
  'engage.ts': ['/api', 'Engagement'],
  'content.ts': ['/api', 'Content'],
  'notifications.ts': ['/api/notifications', 'Notifications'],
  'finance.ts': ['/api', 'Finance'],
  'exams.ts': ['/api', 'Exams'],
  'outcomes.ts': ['/api', 'Outcomes'],
  'admissions.ts': ['/api', 'Admissions'],
  'apply.ts': ['/api/apply', 'Apply (public)'],
  'payments.ts': ['/api/payments', 'Payments'],
};
const VERB: Record<string, string> = { get: 'Get', post: 'Create', put: 'Save', patch: 'Update', delete: 'Delete' };
const schemas = new Set<string>();
const out: string[] = [];
for (const [file, [prefix, tag]] of Object.entries(FILES)) {
  const code = fs.readFileSync(path.join(src, file), 'utf8');
  const re = /(?:^|\n)((?:\/\*\*(?:(?!\*\/)[\s\S])*\*\/\n|\/\/[^\n]*\n)?)(\w*[rR]outer)\.(get|post|patch|put|delete)\('([^']+)'([^\n]*)/g;
  let m;
  while ((m = re.exec(code))) {
    const [, comment, routerName, method, p, rest] = m;
    const start = m.index;
    const next = code.indexOf('\n});', start);
    const body = code.slice(start, next);
    let summary = comment
      .replace(/\/\*\*|\*\/|^\s*\*\s?|\/\/\s?/gm, '')
      .replace(/\s+/g, ' ')
      .trim();
    if (!summary) {
      const words = p.split('/').filter((x) => x && !x.startsWith(':') && !x.startsWith('*')).map((x) => x.replace(/-/g, ' '));
      summary = `${VERB[method]} ${words.slice(-2).join(' ')}`;
    }
    summary = summary.split(/(?<=[.!?])\s/)[0].replace(/\.$/, '').replace(/'/g, '’');
    const perm = /requirePermission\('([a-z_.]+)'\)/.exec(rest)?.[1] ?? (/^\w+, async/.test(rest.trim()) ? null : null);
    const permVar = /, (manage|blueprints),/.exec(rest)?.[1];
    const permission = perm ?? (permVar === 'manage' && file === 'timetable.ts' ? 'timetable.manage' : permVar === 'blueprints' ? 'blueprints.manage' : null);
    const bodySchema = /(\w+Body)\.parse\(req\.body/.exec(body)?.[1];
    const querySchema = /(\w+Query)\.parse\(req\.query/.exec(body)?.[1];
    for (const s of [bodySchema, querySchema]) if (s) schemas.add(s);
    const auth = routerName === 'scormContentRouter' || file === 'payments.ts' || file === 'apply.ts' ? 'public' : 'session';
    const extra = [permission && `permission: '${permission}'`, bodySchema && `body: ${bodySchema}`, querySchema && `query: ${querySchema}`].filter(Boolean);
    out.push(`  r('${method}', '${prefix}${p}', '${tag}', '${summary.slice(0, 160)}', '${auth}'${extra.length ? `, { ${extra.join(', ')} }` : ''}),`);
  }
}
const ts = `// Generated by scripts/gen-openapi-lms.ts from the LMS route files — do not edit by hand.
import {
${[...schemas].sort().map((s) => `  ${s},`).join('\n')}
} from '@acadex/shared';
import type { RouteDoc } from './openapi';

type R = (method: RouteDoc['method'], path: string, tag: string, summary: string, auth: RouteDoc['auth'], extra?: Partial<RouteDoc>) => RouteDoc;

export const lmsRoutes = (r: R): RouteDoc[] => [
${out.join('\n')}
];
`;
fs.writeFileSync(path.join(import.meta.dirname, '..', 'src', 'openapi-lms.ts'), ts);
console.log(`${out.length} routes`);
